def parse_texts(texts: list) -> list:
    # * `+7 999 123-45-67`
    # * `8 999 123-45-67`
    # * `+7 (999) 123-45-67`
    # * `8 (999) 123-45-67`
    
    pattern = re.compile(
        r"(?<!\d)(?:\+7|8)\s(?:\d{3}|\(\d{3}\))\s\d{3}-\d{2}-\d{2}(?!\d)"
    )
    return [re.findall(pattern, text) for text in texts]

